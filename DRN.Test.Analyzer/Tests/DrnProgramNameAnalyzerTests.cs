using System.IO;
using DRN.Framework.Hosting.DrnProgram;
using DRN.Framework.Hosting.Generators;
using DRN.Framework.Testing.DataAttributes;

namespace DRN.Test.Analyzer.Tests;

public class DrnProgramNameAnalyzerTests
{
    private const string ProgramSource = """
        public class BaseProgram : DRN.Framework.Hosting.DrnProgram.DrnProgramBase<BaseProgram>, DRN.Framework.Hosting.DrnProgram.IDrnProgram
        {
            public static System.Threading.Tasks.Task Main(string[] args) => System.Threading.Tasks.Task.CompletedTask;
            protected override System.Threading.Tasks.Task AddServicesAsync(Microsoft.AspNetCore.Builder.WebApplicationBuilder builder,
                DRN.Framework.Utils.Settings.IAppSettings settings, DRN.Framework.Utils.Logging.IScopedLog log)
                => System.Threading.Tasks.Task.CompletedTask;
        }
        """;

    [Theory]
    [DataInlineUnit("SampleProgram", true)]
    [DataInlineUnit("Program", true)]
    [DataInlineUnit("Sampleprogram", false)]
    [DataInlineUnit("SamplePROGRAM", false)]
    [DataInlineUnit("ProgramHost", false)]
    [DataInlineUnit("Host", false)]
    public async Task Analyzer_Should_Require_An_Ordinal_Program_Suffix(string name, bool valid)
    {
        var diagnostics = await Analyze(ProgramSource.Replace("BaseProgram", name, StringComparison.Ordinal));

        if (valid) diagnostics.Should().BeEmpty();
        else AssertSingle(diagnostics, name);
    }

    [Fact]
    public async Task Analyzer_Should_Check_Indirect_Abstract_Generic_And_Nested_Classes()
    {
        var diagnostics = await Analyze(ProgramSource + """
            public abstract class AbstractHost : BaseProgram { }
            public class GenericHost<T> : BaseProgram { }
            public class IndirectHost : GenericHost<int> { }
            public class Container
            {
                private class NestedHost : BaseProgram { }
            }
            public class DerivedProgram : BaseProgram { }
            """);

        diagnostics.Should().HaveCount(4);
        diagnostics.Select(LocationText).Should().BeEquivalentTo("AbstractHost", "GenericHost", "IndirectHost", "NestedHost");
        diagnostics.Should().OnlyContain(diagnostic => diagnostic.Id == "DRNHG002" && diagnostic.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public async Task Analyzer_Should_Resolve_Aliases_And_Report_A_Partial_Class_Once()
    {
        var diagnostics = await Analyze("using HostBase = BaseProgram;\n" + ProgramSource + """
            public partial class AliasedHost : HostBase { }
            public partial class AliasedHost { }
            """);

        AssertSingle(diagnostics, "AliasedHost");
    }

    [Fact]
    public async Task Analyzer_Should_Ignore_Unrelated_Lookalikes_And_Nonclass_Types()
    {
        var diagnostics = await Analyze("""
            namespace Lookalike
            {
                public class DrnProgramBase<T> { }
                public class Host : DrnProgramBase<Host> { }
            }
            public class Unrelated { }
            public struct Value { }
            public interface Contract { }
            """);

        diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task Analyzer_Should_Ignore_Generated_Classes()
    {
        var diagnostics = await Analyze("// <auto-generated/>\n" + ProgramSource.Replace("BaseProgram", "GeneratedHost", StringComparison.Ordinal));

        diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task Analyzer_Should_Resolve_A_Base_From_Referenced_Metadata()
    {
        var library = Compile(ProgramSource, "ProgramLibrary");
        using var stream = new MemoryStream();
        var emission = library.Emit(stream);
        emission.Diagnostics.Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
        emission.Success.Should().BeTrue();
        var reference = MetadataReference.CreateFromImage(stream.ToArray());
        var compilation = Compile("public class ReferencedHost : BaseProgram { }", "Consumer", reference);

        AssertSingle(await Analyze(compilation), "ReferencedHost");
    }

    private static Task<ImmutableArray<Diagnostic>> Analyze(string source) => Analyze(Compile(source));

    private static async Task<ImmutableArray<Diagnostic>> Analyze(CSharpCompilation compilation)
    {
        compilation.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).Should().BeEmpty();
        return await compilation.WithAnalyzers([new DrnProgramNameAnalyzer()]).GetAnalyzerDiagnosticsAsync();
    }

    private static CSharpCompilation Compile(string source, string name = "ProgramNameFixture", params MetadataReference[] additionalReferences)
    {
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
            .Append(typeof(DrnProgramBase<>).Assembly.Location)
            .Distinct(StringComparer.Ordinal).Select(path => MetadataReference.CreateFromFile(path));
        return CSharpCompilation.Create(name, [CSharpSyntaxTree.ParseText(source)], references.Concat(additionalReferences),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }

    private static string LocationText(Diagnostic diagnostic)
        => diagnostic.Location.SourceTree!.GetText().ToString(diagnostic.Location.SourceSpan);

    private static void AssertSingle(ImmutableArray<Diagnostic> diagnostics, string identifier)
    {
        diagnostics.Should().ContainSingle();
        diagnostics[0].Id.Should().Be("DRNHG002");
        diagnostics[0].Severity.Should().Be(DiagnosticSeverity.Error);
        LocationText(diagnostics[0]).Should().Be(identifier);
    }
}
