using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace DRN.Framework.CompilerTools;

internal static class GeneratedSource
{
    internal static bool IsGenerated(SyntaxTree tree, Compilation compilation, AnalyzerConfigOptionsProvider options,
        CancellationToken cancellation)
    {
        cancellation.ThrowIfCancellationRequested();
        var configured = compilation.Options.SyntaxTreeOptionsProvider?.IsGenerated(tree, cancellation);
        if (configured is GeneratedKind.MarkedGenerated or GeneratedKind.NotGenerated)
            return configured == GeneratedKind.MarkedGenerated;
        if (options.GetOptions(tree).TryGetValue("generated_code", out var setting) && bool.TryParse(setting, out var generated))
            return generated;

        var file = Path.GetFileName(tree.FilePath);
        if (file.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase) ||
            file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) || file.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase) ||
            file.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) || file.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase))
            return true;
        foreach (var trivia in tree.GetRoot(cancellation).GetLeadingTrivia())
        {
            if (trivia.Kind() is not (SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia)) continue;
            var comment = trivia.ToString();
            if (comment.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) || comment.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase))
                return true;
        }
        return false;
    }

    internal static Location? FirstUserLocation(ISymbol symbol, SymbolAnalysisContext context)
    {
        foreach (var location in symbol.Locations)
            if (location.SourceTree is { } tree && (symbol.Locations.Length == 1 ||
                !IsGenerated(tree, context.Compilation, context.Options.AnalyzerConfigOptionsProvider, context.CancellationToken)))
                return location;
        return null;
    }
}
